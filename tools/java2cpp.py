# ---------------------------------------------------------------------------
# javalang patches (see the module docstring). These fix two parser bugs
# that silently drop source meaning; without them the translation would be
# wrong. The patches are written against javalang 0.13.0's parser API.
# ---------------------------------------------------------------------------

def _patch_javalang():
    """Patch javalang's parser so no source meaning is lost.

    Patch 1 (default labels): parse_switch_block_statement_group() collects
    the labels of a case group but never records a `default:` label, so a
    default that shares a group with `case` labels vanishes from the AST.
    We record it as the sentinel string "__default__" in the label list.

    Patch 2 (prefix before cast): parse_expression_3() collects unary
    prefix operators, then parses a cast and returns it without attaching
    them, so `-(int)x` loses the minus. We move the collected operators
    onto the cast's inner expression, which does have a prefix slot, so
    `-(int)x` becomes Cast(int, -x) and is emitted as `(int)(-x)`.

    Patch 3 (parenthesized primaries): parse_expression_3() unconditionally
    overwrites the primary's prefix_operators and selectors with its own
    (empty) lists. For a parenthesized expression, parse_primary() returns
    an already-parsed inner node that carries its own prefix operators and
    selectors, so `(byte)(-this.menuItemAvailable[var6])` loses BOTH the
    minus and the `.menuItemAvailable[var6]` selector. We preserve the
    primary's existing prefix operators (prepending ours) and selectors
    instead of overwriting them.
    """
    from javalang.parser import Parser
    from javalang.tree import SwitchStatementCase, Cast
    from javalang import parser as _p

    orig_group = Parser.parse_switch_block_statement_group

    def parse_switch_block_statement_group(self):
        labels = []
        statements = []
        while True:
            case_type = self.tokens.next().value
            if case_type == "case":
                if self.would_accept(jparser.Identifier, ":"):
                    case_value = self.parse_identifier()
                else:
                    case_value = self.parse_expression()
                labels.append(case_value)
            elif case_type == "default":
                labels.append("__default__")
            else:
                self.illegal("Expected switch case")
            self.accept(":")
            if self.tokens.look().value not in ("case", "default"):
                break
        while self.tokens.look().value not in ("case", "default", "}"):
            statements.append(self.parse_block_statement())
        return SwitchStatementCase(case=labels, statements=statements)

    Parser.parse_switch_block_statement_group = parse_switch_block_statement_group

    def parse_expression_3(self):
        from javalang import tree as _tree
        from javalang.parser import Operator
        prefix_operators = []
        while self.tokens.look().value in Operator.PREFIX:
            prefix_operators.append(self.tokens.next().value)
        if self.would_accept("("):
            try:
                with self.tokens:
                    lambda_exp = self.parse_lambda_expression()
                    if lambda_exp:
                        return lambda_exp
            except jparser.JavaSyntaxError:
                pass
            try:
                with self.tokens:
                    self.accept("(")
                    cast_target = self.parse_type()
                    self.accept(")")
                    expression = self.parse_expression_3()
                    if prefix_operators:
                        # The Cast node has no prefix slot; push the
                        # operators onto the inner expression instead.
                        inner = expression
                        existing = list(getattr(inner, "prefix_operators", []) or [])
                        inner.prefix_operators = prefix_operators + existing
                    return Cast(type=cast_target, expression=expression)
            except jparser.JavaSyntaxError:
                pass
        primary = self.parse_primary()
        # A parenthesized expression returns an already-parsed inner node
        # that carries its own prefix operators and selectors; preserve
        # them (prepending our own prefix operators) instead of wiping
        # them. A fresh primary always has empty lists, so this is a no-op
        # for the non-parenthesized case.
        existing_pre = list(getattr(primary, "prefix_operators", None) or [])
        existing_sel = list(getattr(primary, "selectors", None) or [])
        existing_post = list(getattr(primary, "postfix_operators", None) or [])
        primary.prefix_operators = prefix_operators + existing_pre
        primary.selectors = existing_sel
        primary.postfix_operators = existing_post
        token = self.tokens.look()
        while token.value in "[.":
            selector = self.parse_selector()
            selector._position = token.position
            primary.selectors.append(selector)
            token = self.tokens.look()
        while token.value in Operator.POSTFIX:
            primary.postfix_operators.append(self.tokens.next().value)
            token = self.tokens.look()
        return primary

    Parser.parse_expression_3 = parse_expression_3


