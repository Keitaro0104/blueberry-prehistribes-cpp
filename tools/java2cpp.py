class MethodInfo:
    def __init__(self, name, params, return_type, is_static, node):
        self.name = name
        # params: list of (java_name, type descriptor)
        self.params = params
        self.return_type = return_type
        self.is_static = is_static
        self.node = node

    @property
    def signature(self):
        return (self.name, tuple(p[1] for p in self.params))


class FieldInfo:
    def __init__(self, name, type_desc, is_static, node):
        self.name = name
        self.type = type_desc
        self.is_static = is_static
        self.node = node  # the VariableDeclarator


class ClassInfo:
    def __init__(self, name):
        self.name = name
        self.fields = {}          # java name -> FieldInfo
        self.methods = {}         # (name, param-type tuple) -> MethodInfo
        self.methods_by_name = {}  # name -> [MethodInfo]
        self.ctors = []           # [MethodInfo] (name == class name)
        self.superclass = None
        self.interfaces = []
        self.node = None

    def lookup_method(self, name, arg_types):
        """Resolve a call by name + argument types. Returns a MethodInfo
        or None. Exact match first, then widening-compatible, then
        narrowing-compatible. The narrowing pass exists because the
        decompiler sometimes drops a narrowing cast the original source
        had (e.g. setTask(int, byte) called with an int-valued ternary);
        the bytecode narrows the value, and the C++ call does the same
        narrowing implicitly when the argument is passed."""
        cands = self.methods_by_name.get(name, [])
        for m in cands:
            if len(m.params) != len(arg_types):
                continue
            if all(p[1] == a for p, a in zip(m.params, arg_types)):
                return m
        for m in cands:
            if len(m.params) != len(arg_types):
                continue
            if all(types_compatible(p[1], a)
                   for p, a in zip(m.params, arg_types)):
                return m
        for m in cands:
            if len(m.params) != len(arg_types):
                continue
            if all(types_narrowing_compatible(p[1], a)
                   for p, a in zip(m.params, arg_types)):
                return m
        return None

    def lookup_field(self, name):
        return self.fields.get(name)


# Global tables, filled by build_symbol_tables().
CLASSES_INFO = {}   # class name -> ClassInfo
LIB_FIELDS = {}     # library class name -> {field: type} (none for now)


def _modifiers(node):
    return set(getattr(node, "modifiers", None) or [])


def build_symbol_tables():
    for name in CLASSES:
        path = os.path.join(SRC_DIR, name + ".java")
        with open(path, "r", encoding="utf-8") as f:
            src = f.read()
        tree = javalang.parse.parse(src)
        decl = None
        for _, node in tree.filter(T.ClassDeclaration):
            decl = node
            break
        if decl is None or decl.name != name:
            raise TranslateError("%s: class %s not found" % (path, name))
        info = ClassInfo(name)
        info.node = decl
        if decl.extends is not None:
            info.superclass = decl.extends.name
        info.interfaces = [i.name for i in (decl.implements or [])]
        for member in decl.body:
            if isinstance(member, T.FieldDeclaration):
                is_static = "static" in _modifiers(member)
                t = type_from_node(member.type)
                for d in member.declarators:
                    info.fields[d.name] = FieldInfo(d.name, t, is_static, d)
            elif isinstance(member, T.MethodDeclaration):
                is_static = "static" in _modifiers(member)
                params = []
                for p in (member.parameters or []):
                    params.append((p.name, type_from_node(p.type)))
                ret = type_from_node(member.return_type)
                mi = MethodInfo(member.name, params, ret, is_static, member)
                info.methods[mi.signature] = mi
                info.methods_by_name.setdefault(member.name, []).append(mi)
            elif isinstance(member, T.ConstructorDeclaration):
                params = []
                for p in (member.parameters or []):
                    params.append((p.name, type_from_node(p.type)))
                mi = MethodInfo(member.name, params, ("void",), False, member)
                info.ctors.append(mi)
        CLASSES_INFO[name] = info
    return CLASSES_INFO


def all_class_names():
    return set(CLASSES) | set(LIB_CLASSES)


def resolve_class_for_method(class_name, method_name, arg_types):
    """Resolve a method call on a value of class `class_name`. Returns
    (return_type, declaring_class, is_static) or raises TranslateError."""
    # Library classes.
    if class_name in LIB_CLASSES:
        key = (LIB_CLASSES[class_name], method_name)
        # Try the exact library name first, then the Java name.
        if key in LIB_METHODS:
            ret, is_static = LIB_METHODS[key]
            return ret, LIB_CLASSES[class_name], is_static
        key2 = (class_name, method_name)
        if key2 in LIB_METHODS:
            ret, is_static = LIB_METHODS[key2]
            return ret, class_name, is_static
        raise TranslateError("unknown library method %s.%s"
                             % (class_name, method_name))
    # Translated classes.
    info = CLASSES_INFO.get(class_name)
    if info is not None:
        m = info.lookup_method(method_name, arg_types)
        if m is not None:
            return m.return_type, class_name, m.is_static
        # Inherited from a hand-written base class.
        for base in BASES.get(class_name, []):
            try:
                return resolve_class_for_method(base, method_name, arg_types)
            except TranslateError:
                continue
    # Object methods (every Java class has them).
    if method_name in OBJECT_METHODS:
        ret, is_static = LIB_METHODS[("Object", method_name)]
        return ret, "Object", is_static
    raise TranslateError("cannot resolve method %s.%s(%s)"
                         % (class_name, method_name,
                            ", ".join(repr(a) for a in arg_types)))


def resolve_class_for_field(class_name, field_name):
    """Resolve a field access on a value of class `class_name`. Returns
    (type, declaring_class, is_static)."""
    info = CLASSES_INFO.get(class_name)
    if info is not None:
        f = info.lookup_field(field_name)
        if f is not None:
            return f.type, class_name, f.is_static
    if class_name in LIB_FIELDS:
        t = LIB_FIELDS[class_name].get(field_name)
        if t is not None:
            return t, class_name, False
    raise TranslateError("cannot resolve field %s.%s"
                         % (class_name, field_name))


# ---------------------------------------------------------------------------
# Expression emission (pass 2). Every emit_* returns (code, type).
# ---------------------------------------------------------------------------

def _walk(node):
    """Yield every javalang node in the subtree rooted at `node`."""
    if node is None:
        return
    if isinstance(node, (list, tuple)):
        for item in node:
            yield from _walk(item)
        return
    if isinstance(node, T.Node):
        yield node
        for child in node.children:
            yield from _walk(child)


def _plain_var_name(node):
    """The variable name if `node` is a plain variable reference (a local
    or a field of `this` with no qualifier and no selectors), else None.
    Used to recognise assignment targets for the sequencing guard.
    (javalang represents "no qualifier" as an empty string, not None.)"""
    if isinstance(node, T.MemberReference):
        if not node.qualifier and not getattr(node, "selectors", None):
            return node.member
    return None


def _expr_refs_var(node, name):
    """True if `node` references a variable called `name` anywhere
    (reads and writes both count — a write in the other operand is
    just as unsequenced as a read)."""
    for n in _walk(node):
        if isinstance(n, T.MemberReference) and n.member == name:
            return True
    return False


def _expr_assigns_var(node, name):
    """True if `node` assigns to a variable called `name` anywhere."""
    for n in _walk(node):
        if isinstance(n, T.Assignment):
            if _plain_var_name(n.expressionl) == name:
                return True
    return False


class Emitter:
    def __init__(self, class_name):
        self.class_name = class_name
        # Local-variable scopes: a stack of {java name: type descriptor}.
        self.scopes = [{}]
        # Labels of labeled blocks currently being emitted (for `break
        # label;` validation).
        self.block_labels = set()
        # Guard counters (reported at the end of each file).
        self.counts = {"methods": 0, "casts": 0, "string_concat": 0}

    # -- scopes ------------------------------------------------------------
    def push_scope(self):
        self.scopes.append({})

    def pop_scope(self):
        self.scopes.pop()

    def declare_local(self, name, t):
        self.scopes[-1][name] = t

    def lookup_local(self, name):
        for scope in reversed(self.scopes):
            if name in scope:
                return scope[name]
        return None

    def current_is_static(self):
        return getattr(self, "method_is_static", False)

    # -- helpers -----------------------------------------------------------
    def _prefix(self, node):
        ops = getattr(node, "prefix_operators", None) or []
        return ops

    def _postfix(self, node):
        ops = getattr(node, "postfix_operators", None) or []
        return ops

    def _wrap(self, code, node):
        """Apply a node's prefix/postfix operators around its code.
        Multiple prefix operators are joined with a space so that two
        minus signs never merge into the C++ decrement operator (Java
        `- -x` is a double negation, C++ `--x` is a decrement)."""
        pre = self._prefix(node)
        post = self._postfix(node)
        if pre:
            if len(pre) == 1:
                code = pre[0] + code
            else:
                code = " ".join(pre) + " " + code
        if post:
            code = code + "".join(post)
        return code

    def resolve_qualifier(self, qstr):
        """Resolve a dotted identifier chain (a MemberReference /
        MethodInvocation qualifier string) to (code, type, is_class_name).
        is_class_name is True when the chain denotes a class (static
        access), in which case further access uses `::`."""
        parts = qstr.split(".")
        first = parts[0]
        local_t = self.lookup_local(first)
        if local_t is not None:
            code, t, is_class = cpp_name(first), local_t, False
        elif first in CLASSES_INFO.get(self.class_name, ClassInfo("")).fields:
            f = CLASSES_INFO[self.class_name].fields[first]
            code, t, is_class = cpp_name(first), f.type, False
        elif first in all_class_names() or first in ("System",):
            code, t, is_class = first, ("cls", first), True
        else:
            raise TranslateError(
                "%s: cannot resolve qualifier %r" % (self.class_name, qstr))
        for part in parts[1:]:
            if is_class:
                # Static field of a named class.
                ftype, _, _ = resolve_class_for_field(
                    first if first in CLASSES_INFO else first, part)
                code = code + "::" + cpp_name(part)
                t = ftype
                # Stays a class-name chain only if the field is itself a
                # class; fields never are, so clear the flag.
                is_class = False
            elif t[0] == "cls":
                ftype, _, _ = resolve_class_for_field(t[1], part)
                code = code + "->" + cpp_name(part)
                t = ftype
            elif t[0] == "arr" and part == "length":
                code = code + ".size()"
                t = ("prim", "int")
            else:
                raise TranslateError(
                    "%s: cannot resolve qualifier part %r on %r"
                    % (self.class_name, part, t))
        return code, t, is_class

    def apply_selectors(self, code, t, selectors):
        """Apply a selector chain (ArraySelector / MemberReference /
        MethodInvocation) to an already-emitted base expression."""
        for sel in (selectors or []):
            if isinstance(sel, T.ArraySelector):
                idx_code, idx_t = self.emit_expr(sel.index)
                if t[0] != "arr":
                    raise TranslateError(
                        "%s: array index on non-array type %r"
                        % (self.class_name, t))
                code = code + "[" + idx_code + "]"
                t = t[1]
            elif isinstance(sel, T.MemberReference):
                member = sel.member
                if t[0] == "arr" and member == "length":
                    code = code + ".size()"
                    t = ("prim", "int")
                elif t[0] == "cls":
                    ftype, _, _ = resolve_class_for_field(t[1], member)
                    code = code + "->" + cpp_name(member)
                    t = ftype
                else:
                    raise TranslateError(
                        "%s: field %r on type %r"
                        % (self.class_name, member, t))
            elif isinstance(sel, T.MethodInvocation):
                code, t = self.emit_method_on(code, t, sel)
            else:
                raise TranslateError(
                    "%s: unsupported selector %r" % (self.class_name, sel))
        return code, t

    def emit_method_on(self, base_code, base_type, node):
        """Emit a method call on an already-emitted base expression.
        Returns (code, return_type)."""
        name = node.member
        if name == "getClass":
            # Object.getClass() has no C++ member equivalent: every
            # translated class would need one. The only use is
            # `.getResourceAsStream(...)`, served by the JavaClass
            # singleton instead.
            return "JavaClass::instance()", ("cls", "JavaClass")
        arg_codes = []
        arg_types = []
        for a in (node.arguments or []):
            c, t = self.emit_expr(a)
            arg_codes.append(c)
            arg_types.append(t)
        args = ", ".join(arg_codes)
        if base_type[0] == "cls":
            ret, _, is_static = resolve_class_for_method(
                base_type[1], name, arg_types)
            if is_static:
                code = LIB_CLASSES.get(base_type[1], base_type[1]) + "::" + \
                    cpp_name(name) + "(" + args + ")"
            else:
                code = base_code + "->" + cpp_name(name) + "(" + args + ")"
            return code, ret
        if base_type[0] == "str":
            ret, _, _ = resolve_class_for_method("String", name, arg_types)
            return base_code + "." + cpp_name(name) + "(" + args + ")", ret
        if base_type[0] == "obj":
            raise TranslateError(
                "%s: method call %s on java.lang.Object value"
                % (self.class_name, name))
        raise TranslateError(
            "%s: method call %s on type %r"
            % (self.class_name, name, base_type))

    # -- expressions -------------------------------------------------------
    def emit_expr(self, node):
        if node is None:
            raise TranslateError("%s: null expression node"
                                 % self.class_name)
        if isinstance(node, T.Literal):
            code, t = self.emit_literal(node)
        elif isinstance(node, T.This):
            # Selectors are applied uniformly below (a parenthesized
            # `this` can carry selectors, e.g. `(this).foo()`).
            code, t = "this", ("cls", self.class_name)
        elif isinstance(node, T.MemberReference):
            code, t = self.emit_member_ref(node)
        elif isinstance(node, T.MethodInvocation):
            code, t = self.emit_method_inv(node)
        elif isinstance(node, T.ClassCreator):
            code, t = self.emit_class_creator(node)
        elif isinstance(node, T.Cast):
            code, t = self.emit_cast(node)
        elif isinstance(node, T.ArrayCreator):
            code, t = self.emit_array_creator(node)
        elif isinstance(node, T.ArrayInitializer):
            code, t = self.emit_array_initializer(node, None)
        elif isinstance(node, T.BinaryOperation):
            code, t = self.emit_binary_op(node)
        elif isinstance(node, T.TernaryExpression):
            code, t = self.emit_ternary(node)
        elif isinstance(node, T.Assignment):
            code, t = self.emit_assignment(node)
        else:
            raise TranslateError(
                "%s: unsupported expression %s"
                % (self.class_name, type(node).__name__))
        # A parenthesized expression carries its selectors on the node
        # itself (e.g. `(var4 = openRecordStore(...)).getNumRecords()`),
        # so selectors are applied here, uniformly, for every node type.
        # Low-precedence bases (assignment, binary/ternary operators,
        # casts, new-expressions) are parenthesized first: in C++ `->`
        # binds tighter than `=` and a new-expression cannot be followed
        # directly by `->` at all, so `var4 = X->getNumRecords()` would
        # assign a bool and `new T()->m()` would not parse.
        selectors = getattr(node, "selectors", None)
        if selectors and isinstance(
                node, (T.Assignment, T.BinaryOperation, T.TernaryExpression,
                       T.Cast, T.ClassCreator)):
            code = "(" + code + ")"
        code, t = self.apply_selectors(code, t, selectors)
        return self._wrap(code, node), t

    def emit_literal(self, node):
        v = node.value
        if v == "null":
            return "nullptr", ("null",)
        if v == "true":
            return "true", ("prim", "bool")
        if v == "false":
            return "false", ("prim", "bool")
        if v.startswith('"'):
            # Java string escapes match C++ u"..." escapes closely enough
            # (\\ \" \n \t \r \b \f \' \uXXXX, octal) to pass through.
            return "jstr(%s)" % v, ("str",)
        if v.startswith("'"):
            return "u" + v, ("prim", "char16_t")
        # Numeric literal: strip Java digit separators, convert the long
        # suffix to C++.
        num = v.replace("_", "")
        if num[-1] in "Ll":
            return num[:-1] + "LL", ("prim", "int64_t")
        if "." in num or "e" in num or "E" in num:
            raise TranslateError(
                "%s: floating-point literal %r is outside the assumed subset"
                % (self.class_name, v))
        return num, ("prim", "int")

    def emit_member_ref(self, node):
        member = node.member
        qualifier = node.qualifier
        if qualifier:
            base_code, base_type, is_class = self.resolve_qualifier(qualifier)
            if is_class:
                ftype, _, _ = resolve_class_for_field(
                    qualifier.split(".")[0], member)
                code = base_code + "::" + cpp_name(member)
                t = ftype
            elif base_type[0] == "cls":
                ftype, _, _ = resolve_class_for_field(base_type[1], member)
                code = base_code + "->" + cpp_name(member)
                t = ftype
            elif base_type[0] == "arr" and member == "length":
                code = base_code + ".size()"
                t = ("prim", "int")
            elif base_type[0] == "str":
                raise TranslateError(
                    "%s: field %r on String" % (self.class_name, member))
            else:
                raise TranslateError(
                    "%s: field %r on type %r"
                    % (self.class_name, member, base_type))
        else:
            local_t = self.lookup_local(member)
            if local_t is not None:
                code, t = cpp_name(member), local_t
            else:
                info = CLASSES_INFO[self.class_name]
                f = info.lookup_field(member)
                if f is not None:
                    code, t = cpp_name(member), f.type
                else:
                    raise TranslateError(
                        "%s: unknown identifier %r"
                        % (self.class_name, member))
        return code, t

    def emit_method_inv(self, node):
        name = node.member
        qualifier = node.qualifier
        arg_codes = []
        arg_types = []
        for a in (node.arguments or []):
            c, t = self.emit_expr(a)
            arg_codes.append(c)
            arg_types.append(t)
        args = ", ".join(arg_codes)
        if not qualifier:
            # Unqualified call: current class, then its bases, then Object.
            if name == "getClass":
                return "JavaClass::instance()", ("cls", "JavaClass")
            info = CLASSES_INFO[self.class_name]
            m = info.lookup_method(name, arg_types)
            if m is not None:
                return cpp_name(name) + "(" + args + ")", m.return_type
            for base in BASES.get(self.class_name, []):
                try:
                    ret, _, _ = resolve_class_for_method(
                        base, name, arg_types)
                    return cpp_name(name) + "(" + args + ")", ret
                except TranslateError:
                    continue
            if name in OBJECT_METHODS:
                ret, _ = LIB_METHODS[("Object", name)]
                return cpp_name(name) + "(" + args + ")", ret
            raise TranslateError(
                "%s: cannot resolve unqualified call %s(%s)"
                % (self.class_name, name,
                   ", ".join(repr(a) for a in arg_types)))
        if qualifier == "System":
            if name == "arraycopy":
                if len(arg_codes) != 5:
                    raise TranslateError("System.arraycopy needs 5 args")
                return ("arraycopy(%s, %s, %s, %s, %s)"
                        % tuple(arg_codes)), ("prim", "void")
            if name == "gc":
                return "jlang::gc()", ("prim", "void")
            if name == "currentTimeMillis":
                return "jlang::currentTimeMillis()", ("prim", "int64_t")
            raise TranslateError("%s: unknown System.%s"
                                 % (self.class_name, name))
        base_code, base_type, is_class = self.resolve_qualifier(qualifier)
        if is_class:
            ret, _, is_static = resolve_class_for_method(
                qualifier.split(".")[0], name, arg_types)
            if not is_static:
                raise TranslateError(
                    "%s: static call to instance method %s.%s"
                    % (self.class_name, qualifier, name))
            cls = LIB_CLASSES.get(qualifier.split(".")[0],
                                  qualifier.split(".")[0])
            return cls + "::" + cpp_name(name) + "(" + args + ")", ret
        return self.emit_method_on(base_code, base_type, node)

    def emit_class_creator(self, node):
        tnode = node.type
        if not isinstance(tnode, T.ReferenceType):
            raise TranslateError("%s: unexpected creator type %r"
                                 % (self.class_name, tnode))
        name = tnode.name
        arg_codes = []
        for a in (node.arguments or []):
            c, _ = self.emit_expr(a)
            arg_codes.append(c)
        args = ", ".join(arg_codes)
        if name == "String":
            # `new String(...)` does not occur in this codebase; the
            # String value type is constructed directly if it ever does.
            code = "String(" + args + ")"
            t = ("str",)
        else:
            cls = LIB_CLASSES.get(name, name)
            code = "new " + cls + "(" + args + ")"
            t = ("cls", name)
        return code, t

    def emit_cast(self, node):
        self.counts["casts"] += 1
        code, t = self.emit_expr(node.expression)
        target = type_from_node(node.type)
        if target[0] == "prim" and t[0] == "prim":
            return "(" + cpp_type(target) + ")(" + code + ")", target
        if target[0] == "cls":
            return ("static_cast<" + LIB_CLASSES.get(target[1], target[1]) +
                    "*>(" + code + ")"), target
        if target == ("str",):
            return code, target
        if target == ("obj",):
            return "(void*)(" + code + ")", target
        pos = getattr(node, "position", None)
        raise TranslateError(
            "%s: unsupported cast to %r from %r (at %s)"
            % (self.class_name, target, t, pos))

    def emit_array_initializer(self, node, elem_type):
        parts = []
        for init in (node.initializers or []):
            if isinstance(init, T.ArrayInitializer):
                # Nested initializer: element type is one dimension down.
                inner_elem = elem_type[1] if elem_type and elem_type[0] == "arr" else None
                c, _ = self.emit_array_initializer(init, inner_elem)
                parts.append(c)
            else:
                c, _ = self.emit_expr(init)
                if elem_type and elem_type[0] == "prim":
                    # Narrowing in a braced list is an error in C++ when
                    # the value does not fit; make it explicit (Java does
                    # the same narrowing when storing into the array).
                    c = "(" + cpp_type(elem_type) + ")(" + c + ")"
                parts.append(c)
        if elem_type is None:
            return "{" + ", ".join(parts) + "}", ("unknown",)
        return ("newArr<" + cpp_type(elem_type) + ">({" +
                ", ".join(parts) + "})"), ("arr", elem_type)

    def emit_array_creator(self, node):
        # The element type is node.type; the array dimensions live on the
        # ArrayCreator node (node.dimensions), not on the type node.
        base = type_from_node(node.type)
        dims = node.dimensions or []
        t = base
        for _ in dims:
            t = ("arr", t)
        if node.initializer is not None:
            # new T[]{...} — the initializer determines the contents.
            return self.emit_array_initializer(node.initializer, t[1])
        # new T[d1][d2]... — some trailing dimensions may be unspecified
        # (jagged arrays): only the leading specified dimensions are
        # allocated, the rest stay null like Java.
        dim_codes = []
        specified = 0
        for d in dims:
            if d is None:
                dim_codes.append(None)
            else:
                c, _ = self.emit_expr(d)
                dim_codes.append(c)
                specified += 1
        if specified == len(dims):
            # Fully specified: newArrN<innermost>(d1, d2, ...).
            inner = t
            while inner[0] == "arr":
                inner = inner[1]
            n = len(dims)
            maker = "newArr" if n == 1 else "newArr%d" % n
            return ("%s<%s>(%s)" % (maker, cpp_type(inner),
                                    ", ".join(dim_codes))), t
        # Jagged: allocate the leading dimensions of nested Arr values.
        leading = 0
        while leading < len(dims) and dim_codes[leading] is not None:
            leading += 1
        inner = t
        for _ in range(leading):
            inner = inner[1]
        # `inner` is now the type of the array elements at the deepest
        # allocated level (still an Arr<...> if trailing dims are None).
        maker = "newArr" if leading == 1 else "newArr%d" % leading
        return ("%s<%s>(%s)" % (maker, cpp_type(inner),
                                ", ".join(dim_codes[:leading]))), t

    def _check_binary_sequencing(self, node):
        """Fail loudly on binary-operator shapes whose Java evaluation
        order C++ cannot reproduce. The comma rewrite in emit_binary_op
        covers the one safe shape (the left operand IS the assignment);
        every other shape — an assignment nested inside an operand, or
        an assignment in the right operand read by the left — is
        undefined behaviour in C++ and must surface here, not in a
        silently wrong binary."""
        for side, other in ((node.operandl, node.operandr),
                            (node.operandr, node.operandl)):
            for n in _walk(side):
                if not isinstance(n, T.Assignment):
                    continue
                if n.type.strip("'") != "=":
                    continue
                name = _plain_var_name(n.expressionl)
                if name is None:
                    continue
                # The rewrite shape (the left operand is itself the
                # assignment) is handled by emit_binary_op, not an error.
                if side is node.operandl and n is node.operandl:
                    continue
                if _expr_refs_var(other, name):
                    raise TranslateError(
                        "%s: unsequenced assignment to %r in a binary "
                        "operator (Java evaluates left-to-right, C++ does "
                        "not) — outside the translator's subset"
                        % (self.class_name, name))

    def _binary_result_type(self, op, lt, rt):
        """The result type of a binary operator, mirroring the normal
        path in emit_binary_op (used by the comma rewrite so it returns
        the same type as the un-rewritten operator)."""
        if op == "+" and (lt == ("str",) or rt == ("str",)):
            return ("str",)
        if op in ("==", "!=", "<", "<=", ">", ">="):
            return ("prim", "bool")
        if op in ("<<", ">>"):
            return ("prim", "int64_t") if lt == ("prim", "int64_t") \
                else ("prim", "int")
        if lt == ("prim", "int64_t") or rt == ("prim", "int64_t"):
            return ("prim", "int64_t")
        if lt == ("prim", "double") or rt == ("prim", "double"):
            return ("prim", "double")
        if lt == ("prim", "float") or rt == ("prim", "float"):
            return ("prim", "float")
        return ("prim", "int")

    def emit_binary_op(self, node):
        op = node.operator.strip("'")
        if op == "instanceof":
            raise TranslateError(
                "%s: instanceof is outside the assumed subset"
                % self.class_name)
        # --- sequencing guard -------------------------------------------
        # Java evaluates the operands of a binary operator left to right.
        # C++ leaves them unsequenced (except && and ||, which sequence
        # left-before-right and short-circuit, matching Java), so an
        # assignment in one operand and a reference to the same variable
        # in the other is undefined behaviour in C++: the reference may
        # see the old value. The one site in the game that does this is
        #   var7 = (var13 = (byte)(...)) * var13;
        # (a nearest-entity distance in Game), where Java squares the
        # NEW var13 and C++ might multiply by the OLD one.
        if op not in ("&&", "||"):
            self._check_binary_sequencing(node)
        lcode, lt = self.emit_expr(node.operandl)
        rcode, rt = self.emit_expr(node.operandr)
        # The observed shape: (V = X) OP R, where R reads V. Force the
        # Java order with a comma expression — the assignment runs first,
        # then V OP R is evaluated with the new value. This must not fire
        # when R itself assigns to V (that would still be unsequenced).
        if (op not in ("&&", "||")
                and isinstance(node.operandl, T.Assignment)
                and node.operandl.type.strip("'") == "="
                and _plain_var_name(node.operandl.expressionl) is not None
                and _expr_refs_var(node.operandr,
                                   _plain_var_name(node.operandl.expressionl))
                and not _expr_assigns_var(
                    node.operandr,
                    _plain_var_name(node.operandl.expressionl))):
            vcode, _ = self.emit_expr(node.operandl.expressionl)
            res = self._binary_result_type(op, lt, rt)
            return ("((" + lcode + "), (" + vcode + " " + op + " " + rcode +
                    "))"), res
        if op == "+" and (lt == ("str",) or rt == ("str",)):
            self.counts["string_concat"] += 1
            if lt[0] == "cls" or rt[0] == "cls":
                raise TranslateError(
                    "%s: string concatenation with object operand"
                    % self.class_name)
            if lt[0] == "arr" or rt[0] == "arr":
                raise TranslateError(
                    "%s: string concatenation with array operand"
                    % self.class_name)
            return "(" + lcode + " + " + rcode + ")", ("str",)
        if op in ("==", "!=") and lt == ("str",) and rt == ("str",):
            # String::operator== is reference equality (like Java ==);
            # value equality is .equals(). Both are valid C++ here.
            pass
        if op in ("==", "!=") and lt[0] == "arr" and rt[0] == "arr":
            # Arr::operator== is reference equality (like Java ==).
            pass
        if op in ("&&", "||"):
            return "(" + lcode + " " + op + " " + rcode + ")", ("prim", "bool")
        if op in ("==", "!=", "<", "<=", ">", ">="):
            return "(" + lcode + " " + op + " " + rcode + ")", ("prim", "bool")
        if op in ("<<", ">>"):
            # Java: result type is the left operand's type (byte/short/
            # char promoted to int).
            res = ("prim", "int64_t") if lt == ("prim", "int64_t") else ("prim", "int")
            return "(" + lcode + " " + op + " " + rcode + ")", res
        if op in ("+", "-", "*", "/", "%", "&", "|", "^"):
            if lt == ("prim", "int64_t") or rt == ("prim", "int64_t"):
                res = ("prim", "int64_t")
            elif lt == ("prim", "double") or rt == ("prim", "double"):
                res = ("prim", "double")
            elif lt == ("prim", "float") or rt == ("prim", "float"):
                res = ("prim", "float")
            else:
                res = ("prim", "int")
            return "(" + lcode + " " + op + " " + rcode + ")", res
        raise TranslateError("%s: unsupported operator %r"
                             % (self.class_name, op))

    def emit_ternary(self, node):
        ccode, _ = self.emit_expr(node.condition)
        tcode, tt = self.emit_expr(node.if_true)
        fcode, ft = self.emit_expr(node.if_false)
        if tt == ("null",):
            res = ft
        elif ft == ("null",):
            res = tt
        elif tt == ft:
            res = tt
        elif is_numeric(tt) and is_numeric(ft):
            res = ("prim", "int64_t") if ("prim", "int64_t") in (tt, ft) \
                else ("prim", "int")
        else:
            raise TranslateError(
                "%s: ternary with mismatched branch types %r / %r"
                % (self.class_name, tt, ft))
        return "(" + ccode + " ? " + tcode + " : " + fcode + ")", res

    def emit_assignment(self, node):
        op = node.type.strip("'")
        if op == ">>>=":
            raise TranslateError("%s: >>>= is outside the assumed subset"
                                 % self.class_name)
        lcode, lt = self.emit_expr(node.expressionl)
        rcode, _ = self.emit_expr(node.value)
        # Always parenthesize: an assignment used as an operand (e.g.
        # `(var1 = getResourceAsStream(...)) != null`) would otherwise
        # bind the wrong way in C++ (`=` is looser than `!=`/`->`).
        if op == "=":
            return "(" + lcode + " = " + rcode + ")", lt
        return "(" + lcode + " " + op + " " + rcode + ")", lt


def _has_captured_break(stmts):
    """True if `stmts` contains an unlabeled `break` that would be
    captured by a do-while (false) wrapper, i.e. a break whose target is
    outside the block. Breaks inside nested loops/switches target those
    constructs, not the wrapper, so the scan does not descend into them."""
    for s in (stmts or []):
        if isinstance(s, T.BreakStatement):
            if not getattr(s, "goto", None):
                return True
        elif isinstance(s, (T.ForStatement, T.WhileStatement,
                            T.DoStatement, T.SwitchStatement)):
            continue
        elif isinstance(s, T.BlockStatement):
            if _has_captured_break(s.statements):
                return True
        elif isinstance(s, T.IfStatement):
            for branch in (s.then_statement, s.else_statement):
                if branch is not None:
                    inner = (branch.statements
                             if isinstance(branch, T.BlockStatement)
                             else [branch])
                    if _has_captured_break(inner):
                        return True
        elif isinstance(s, T.TryStatement):
            if _has_captured_break(s.block):
                return True
            for catch in (s.catches or []):
                if _has_captured_break(catch.block):
                    return True
    return False


