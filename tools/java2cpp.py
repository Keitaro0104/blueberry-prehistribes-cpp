#!/usr/bin/env python3
"""Mechanical Java -> C++ translator for the Prehistoric Tribes port.

Reads the renamed Java in tribes/src/ (produced by tools/rename_tribes.py)
and emits tribes/port/src/gen/classes.h plus one .cpp per translated class.
The generated files carry a "Generated by tools/java2cpp.py - do not edit"
header; never hand-edit them, regenerate instead.

Design (same pattern as the GOW Betrayal port, own implementation):
  * Parse with javalang, after patching two javalang parser bugs that would
    silently drop source meaning:
      - a `default:` label sharing a case group with `case` labels is
        dropped by the stock parser (Game.keyPressed and World lose one
        each); the patch records it as a "__default__" label.
      - a unary prefix operator before a cast, e.g. `-(int)x`, is dropped
        by the stock parser (Cast has no prefix_operators slot); the patch
        moves the operator onto the cast's inner expression.
  * Two passes: first build a symbol table for every class (fields, methods,
    constructors, superclass, interfaces), then emit. Method calls are
    resolved against the table so the translator knows each call's return
    type and whether to emit `.` / `->` / `::`.
  * Type mapping: Java classes -> raw pointers, arrays -> bounds-checked
    Arr<T> (shared_ptr-backed, so assignment aliases like Java), String ->
    immutable UTF-16 value type, primitives -> fixed-width C++ types,
    static fields -> `inline static`.
  * MIDP classes map to hand-written C++ stand-ins (Graphics -> Surface,
    Image -> Image, DataInputStream, Random, StringBuffer, MIDlet, Display,
    Font, Player). See tribes/docs/TRANSLATOR-NOTES.md for the full table.
  * Assumed subset (verified by the pre-flight check in main()): no
    generics, lambdas, floats, finally blocks, throw, synchronized,
    instanceof, or enhanced-for loops. If any of these appear, the
    translator fails loudly instead of silently mishandling them.
  * Regression guards: after emitting each file, count checks verify that
    the generated code contains the same number of methods as the Java
    input, and that no operator was dropped (the javalang patches above
    are part of that guarantee).

Usage:
    python3 tools/java2cpp.py [--check-only]
"""

