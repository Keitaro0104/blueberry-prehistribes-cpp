class StmtEmitter(Emitter):
    def emit_block(self, stmts, indent):
        lines = []
        for s in (stmts or []):
            lines.extend(self.emit_stmt(s, indent))
        return lines

    def emit_stmt(self, node, indent):
        pad = "   " * indent
        if isinstance(node, T.BlockStatement):
            label = getattr(node, "label", None)
            if label:
                # A labeled block (`label42: { ... break label42; ... }`)
                # is Vineflower's idiom for "break out of this block".
                # C++ has no labeled break, so emit it as a do-while
                # (false) loop and translate `break label;` to `break;`.
                # An unlabeled break inside would be captured by the
                # do-while instead of its intended target, so that case
                # fails loudly.
                if _has_captured_break(node.statements):
                    raise TranslateError(
                        "%s: labeled block %r contains an unlabeled break"
                        % (self.class_name, label))
                self.block_labels.add(label)
                lines = [pad + "do {"]
                self.push_scope()
                lines.extend(self.emit_block(node.statements, indent + 1))
                self.pop_scope()
                lines.append(pad + "} while (false);")
                self.block_labels.discard(label)
                return lines
            self.push_scope()
            lines = [pad + "{"]
            lines.extend(self.emit_block(node.statements, indent + 1))
            self.pop_scope()
            lines.append(pad + "}")
            return lines
        if isinstance(node, T.VariableDeclaration):
            # LocalVariableDeclaration in statement position, or
            # VariableDeclaration as a for-loop initializer.
            t = type_from_node(node.type)
            parts = []
            for d in node.declarators:
                init = d.initializer
                if init is not None:
                    if isinstance(init, T.ArrayInitializer):
                        icode, _ = self.emit_array_initializer(init, t[1])
                    else:
                        icode, _ = self.emit_expr(init)
                    parts.append("%s %s = %s" % (cpp_type(t), cpp_name(d.name), icode))
                else:
                    parts.append("%s %s{}" % (cpp_type(t), cpp_name(d.name)))
                self.declare_local(d.name, t)
            return [pad + ", ".join(parts) + ";"]
        if isinstance(node, T.StatementExpression):
            code, _ = self.emit_expr(node.expression)
            return [pad + code + ";"]
        if isinstance(node, T.IfStatement):
            code, _ = self.emit_expr(node.condition)
            lines = [pad + "if (" + code + ") {"]
            self.push_scope()
            lines.extend(self.emit_block(
                node.then_statement.statements
                if isinstance(node.then_statement, T.BlockStatement)
                else [node.then_statement], indent + 1))
            self.pop_scope()
            if node.else_statement is not None:
                lines.append(pad + "} else {")
                self.push_scope()
                lines.extend(self.emit_block(
                    node.else_statement.statements
                    if isinstance(node.else_statement, T.BlockStatement)
                    else [node.else_statement], indent + 1))
                self.pop_scope()
            lines.append(pad + "}")
            return lines
        if isinstance(node, T.ForStatement):
            return self.emit_for(node, indent)
        if isinstance(node, T.WhileStatement):
            code, _ = self.emit_expr(node.condition)
            lines = [pad + "while (" + code + ") {"]
            self.push_scope()
            lines.extend(self.emit_block(
                node.body.statements
                if isinstance(node.body, T.BlockStatement)
                else [node.body], indent + 1))
            self.pop_scope()
            lines.append(pad + "}")
            return lines
        if isinstance(node, T.DoStatement):
            lines = [pad + "do {"]
            self.push_scope()
            lines.extend(self.emit_block(
                node.body.statements
                if isinstance(node.body, T.BlockStatement)
                else [node.body], indent + 1))
            self.pop_scope()
            code, _ = self.emit_expr(node.condition)
            lines.append(pad + "} while (" + code + ");")
            return lines
        if isinstance(node, T.ReturnStatement):
            if node.expression is None:
                return [pad + "return;"]
            code, _ = self.emit_expr(node.expression)
            return [pad + "return " + code + ";"]
        if isinstance(node, T.BreakStatement):
            target = getattr(node, "goto", None)
            if target:
                if target not in self.block_labels:
                    raise TranslateError(
                        "%s: labeled break to %r (not a labeled block)"
                        % (self.class_name, target))
                return [pad + "break;"]
            return [pad + "break;"]
        if isinstance(node, T.ContinueStatement):
            if getattr(node, "goto", None):
                raise TranslateError("%s: labeled continue is outside the "
                                     "assumed subset" % self.class_name)
            return [pad + "continue;"]
        if isinstance(node, T.TryStatement):
            return self.emit_try(node, indent)
        if isinstance(node, T.SwitchStatement):
            return self.emit_switch(node, indent)
        if isinstance(node, T.EmptyStatement):
            return [pad + ";"]
        raise TranslateError("%s: unsupported statement %s"
                             % (self.class_name, type(node).__name__))

    def emit_for(self, node, indent):
        pad = "   " * indent
        control = node.control
        self.push_scope()
        init_code = ""
        if control.init is not None:
            if isinstance(control.init, T.VariableDeclaration):
                # For-loop variable declaration (a VariableDeclaration,
                # not a LocalVariableDeclaration, in javalang 0.13).
                t = type_from_node(control.init.type)
                parts = []
                for d in control.init.declarators:
                    if d.initializer is not None:
                        if isinstance(d.initializer, T.ArrayInitializer):
                            icode, _ = self.emit_array_initializer(
                                d.initializer, t[1])
                        else:
                            icode, _ = self.emit_expr(d.initializer)
                        parts.append("%s %s = %s"
                                     % (cpp_type(t), cpp_name(d.name), icode))
                    else:
                        parts.append("%s %s{}"
                                     % (cpp_type(t), cpp_name(d.name)))
                    self.declare_local(d.name, t)
                init_code = ", ".join(parts)
            else:
                parts = []
                for expr in control.init:
                    c, _ = self.emit_expr(expr)
                    parts.append(c)
                init_code = ", ".join(parts)
        cond_code = ""
        if control.condition is not None:
            cond_code, _ = self.emit_expr(control.condition)
        update_code = ""
        if control.update:
            parts = []
            for expr in control.update:
                c, _ = self.emit_expr(expr)
                parts.append(c)
            update_code = ", ".join(parts)
        lines = [pad + "for (%s; %s; %s) {" % (init_code, cond_code, update_code)]
        lines.extend(self.emit_block(
            node.body.statements
            if isinstance(node.body, T.BlockStatement)
            else [node.body], indent + 1))
        self.pop_scope()
        lines.append(pad + "}")
        return lines

    def emit_try(self, node, indent):
        pad = "   " * indent
        if node.finally_block is not None:
            raise TranslateError("%s: finally blocks are outside the "
                                 "assumed subset" % self.class_name)
        lines = [pad + "try {"]
        self.push_scope()
        lines.extend(self.emit_block(node.block, indent + 1))
        self.pop_scope()
        for catch in (node.catches or []):
            param = catch.parameter
            # All caught Java exception types map to the single
            # JavaException runtime type (see jrt.h). The catch bodies
            # never call methods on the exception object.
            pname = cpp_name(param.name)
            lines.append(pad + "} catch (JavaException& " + pname + ") {")
            self.push_scope()
            self.declare_local(param.name, ("cls", "JavaException"))
            lines.extend(self.emit_block(catch.block, indent + 1))
            self.pop_scope()
        lines.append(pad + "}")
        return lines

    def emit_switch(self, node, indent):
        pad = "   " * indent
        code, _ = self.emit_expr(node.expression)
        lines = [pad + "switch (" + code + ") {"]
        for case in node.cases:
            labels = []
            for label in case.case:
                if label == "__default__":
                    labels.append("default")
                else:
                    lcode, _ = self.emit_expr(label)
                    labels.append("case " + lcode)
            for label in labels:
                lines.append(pad + "   " + label + ":")
            self.push_scope()
            lines.extend(self.emit_block(case.statements, indent + 1))
            self.pop_scope()
        lines.append(pad + "}")
        return lines


