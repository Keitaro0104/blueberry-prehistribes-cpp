class TranslateError(Exception):
    """Raised when the translator cannot faithfully translate a construct."""


def cpp_name(name):
    """Rename a Java identifier that would collide with C++."""
    if name in RESERVED:
        return name + "_"
    return name


def cpp_type(t):
    """Render a type descriptor as a C++ type string."""
    kind = t[0]
    if kind == "prim":
        return t[1]
    if kind == "str":
        return "String"
    if kind == "cls":
        return LIB_CLASSES.get(t[1], t[1]) + "*"
    if kind == "arr":
        return "Arr<" + cpp_type(t[1]) + ">"
    if kind == "void":
        return "void"
    if kind == "null":
        return "std::nullptr_t"
    if kind == "obj":
        return "void*"
    raise TranslateError("cannot render type %r" % (t,))


def type_from_node(node):
    """Build a type descriptor from a javalang type node."""
    if node is None:
        # javalang represents a void method return type as None.
        return ("prim", "void")
    if isinstance(node, T.BasicType):
        base = ("prim", PRIM_MAP[node.name])
        dims = node.dimensions or []
        t = base
        for _ in dims:
            t = ("arr", t)
        return t
    if isinstance(node, T.ReferenceType):
        name = node.name
        if name == "String":
            base = ("str",)
        elif name == "Object":
            # java.lang.Object: only used for an unused dead local and the
            # unused playerUpdate event-data parameter. void* holds any
            # pointer (and nullptr); no methods are ever called on it.
            base = ("obj",)
        else:
            base = ("cls", name)
        dims = node.dimensions or []
        t = base
        for _ in dims:
            t = ("arr", t)
        return t
    raise TranslateError("unsupported type node %r" % (node,))


def is_numeric(t):
    return t[0] == "prim" and t[1] in (
        "int", "int8_t", "int16_t", "int64_t", "char16_t", "float", "double")


def is_integral(t):
    return t[0] == "prim" and t[1] in (
        "int", "int8_t", "int16_t", "int64_t", "char16_t")


def types_compatible(param, arg):
    """Whether an argument of type `arg` can be passed to a parameter of
    type `param` (Java widening rules, simplified)."""
    if param == arg:
        return True
    if arg == ("null",):
        return param[0] in ("cls", "arr", "str", "obj")
    if param == ("obj",):
        return arg[0] in ("cls", "arr", "str", "null")
    if param[0] == "prim" and arg[0] == "prim":
        # Widening: byte/short/char -> int -> long; int -> long.
        order = {"int8_t": 0, "int16_t": 0, "char16_t": 0, "int": 1,
                 "int64_t": 2, "float": 3, "double": 4}
        return order.get(param[1], -1) >= order.get(arg[1], -1)
    if param[0] == "arr" and arg[0] == "arr":
        return types_compatible(param[1], arg[1])
    return False


def types_narrowing_compatible(param, arg):
    """Whether an argument of type `arg` can be passed to a parameter of
    type `param` by a narrowing numeric conversion (Java allows this only
    for constant expressions; the decompiler drops such casts, so the
    translator accepts the narrowing and relies on the C++ call doing the
    same narrowing implicitly)."""
    if types_compatible(param, arg):
        return True
    return is_numeric(param) and is_numeric(arg)


