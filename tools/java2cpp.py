HEADER = """// Generated by tools/java2cpp.py -- do not edit.
// Regenerate with: python3 tools/java2cpp.py
"""

def _params_decl(params):
    return ", ".join("%s %s" % (cpp_type(t), cpp_name(n)) for n, t in params)


def emit_class_header(info, emitter):
    lines = []
    lines.append("// " + info.name + " (translated from tribes/src/" +
                 info.name + ".java)")
    bases = BASES.get(info.name, [])
    if bases:
        lines.append("class %s : public %s {" %
                     (info.name, ", public ".join(bases)))
    else:
        lines.append("class %s {" % info.name)
    lines.append(" public:")
    # Constructors.
    for ctor in info.ctors:
        lines.append("  %s(%s);" % (info.name, _params_decl(ctor.params)))
    # Methods.
    for sig in sorted(info.methods):
        m = info.methods[sig]
        ret = cpp_type(m.return_type)
        static = "static " if m.is_static else ""
        override = " override" if m.name in OVERRIDES.get(info.name, set()) else ""
        lines.append("  %s%s %s(%s)%s;" %
                     (static, ret, cpp_name(m.name), _params_decl(m.params),
                      override))
    # Fields (all public: the original Java relies on package-private
    # access between these classes, which has no C++ equivalent).
    for name in info.fields:
        f = info.fields[name]
        decl = cpp_name(name)
        if f.is_static:
            prefix = "  inline static "
        else:
            prefix = "  "
        init = f.node.initializer
        if init is not None:
            if isinstance(init, T.ArrayInitializer):
                icode, _ = emitter.emit_array_initializer(init, f.type[1])
            else:
                icode, _ = emitter.emit_expr(init)
            lines.append("%s%s %s = %s;" % (prefix, cpp_type(f.type), decl, icode))
        else:
            # Value-initialize: Java fields default to 0/false/null, C++
            # leaves primitives uninitialized without this.
            lines.append("%s%s %s{};" % (prefix, cpp_type(f.type), decl))
    lines.append("};")
    lines.append("")
    return lines


def emit_class_cpp(info):
    lines = []
    lines.append('#include "gen/classes.h"')
    lines.append("")
    emitter = StmtEmitter(info.name)
    # Constructors.
    for ctor in info.ctors:
        lines.append("%s::%s(%s) {" % (info.name, info.name,
                                       _params_decl(ctor.params)))
        emitter.scopes = [{}]
        emitter.method_is_static = False
        for n, t in ctor.params:
            emitter.declare_local(n, t)
        lines.extend(emitter.emit_block(ctor.node.body, 1))
        lines.append("}")
        lines.append("")
    # Methods.
    for sig in sorted(info.methods):
        m = info.methods[sig]
        ret = cpp_type(m.return_type)
        lines.append("%s %s::%s(%s) {" % (ret, info.name, cpp_name(m.name),
                                          _params_decl(m.params)))
        emitter.scopes = [{}]
        emitter.method_is_static = m.is_static
        emitter.counts["methods"] += 1
        for n, t in m.params:
            emitter.declare_local(n, t)
        body = m.node.body or []
        lines.extend(emitter.emit_block(body, 1))
        lines.append("}")
        lines.append("")
    return lines, emitter.counts


# ---------------------------------------------------------------------------
# Pre-flight check: fail loudly if the input contains anything outside the
# assumed subset, instead of silently mishandling it.
# ---------------------------------------------------------------------------

FORBIDDEN = [
    (T.LambdaExpression, "lambda expression"),
    (T.MethodReference, "method reference"),
    (T.ThrowStatement, "throw statement"),
    (T.SynchronizedStatement, "synchronized block"),
    (T.AssertStatement, "assert statement"),
    (T.EnhancedForControl, "enhanced-for loop"),
]


def preflight(tree, path):
    problems = []
    for node_type, label in FORBIDDEN:
        for _, _n in tree.filter(node_type):
            problems.append("%s: %s" % (path, label))
    # TypeDeclaration matches the top-level class itself; only a second
    # one in the file means a nested type.
    n_types = sum(1 for _ in tree.filter(T.TypeDeclaration))
    if n_types > 1:
        problems.append("%s: nested type declaration" % path)
    for _, n in tree.filter(T.TryStatement):
        if n.finally_block is not None:
            problems.append("%s: finally block" % path)
    for _, n in tree.filter(T.Literal):
        v = n.value
        if v and ("." in v or "e" in v or "E" in v) and v[0].isdigit():
            problems.append("%s: floating-point literal %r" % (path, v))
    for _, n in tree.filter(T.BinaryOperation):
        if n.operator.strip("'") in (">>>", ">>>="):
            problems.append("%s: unsigned shift operator" % path)
    return problems


def main(argv):
    _patch_javalang()
    check_only = "--check-only" in argv
    build_symbol_tables()
    problems = []
    trees = {}
    for name in CLASSES:
        path = os.path.join(SRC_DIR, name + ".java")
        with open(path, "r", encoding="utf-8") as f:
            src = f.read()
        tree = javalang.parse.parse(src)
        trees[name] = tree
        problems.extend(preflight(tree, path))
    if problems:
        print("Pre-flight check FAILED (%d problem(s)):" % len(problems))
        for p in sorted(set(problems))[:40]:
            print("  " + p)
        return 1
    if check_only:
        print("Pre-flight check passed: no constructs outside the assumed "
              "subset.")
        return 0

    os.makedirs(OUT_DIR, exist_ok=True)
    # classes.h
    header_lines = [HEADER, "#pragma once", "",
                    '#include "../jrt.h"',
                    '#include "../gfx.h"',
                    '#include "../engine.h"',
                    '#include "../platform.h"', ""]
    for name in CLASSES:
        header_lines.append("class %s;" % name)
    header_lines.append("")
    total_methods = 0
    for name in CLASSES:
        info = CLASSES_INFO[name]
        emitter = StmtEmitter(name)
        header_lines.extend(emit_class_header(info, emitter))
        total_methods += len(info.methods)
    with open(os.path.join(OUT_DIR, "classes.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(header_lines))

    # One .cpp per class.
    total_lines = 0
    for name in CLASSES:
        info = CLASSES_INFO[name]
        lines, counts = emit_class_cpp(info)
        out = [HEADER] + lines
        path = os.path.join(OUT_DIR, name + ".cpp")
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(out))
        total_lines += len(out)
        print("%s: %d methods, %d casts, %d string concats -> %s (%d lines)"
              % (name, len(info.methods), counts["casts"],
                 counts["string_concat"], path, len(out)))

    print("classes.h + %d .cpp files written to %s" % (len(CLASSES), OUT_DIR))
    print("Total methods translated: %d" % total_methods)
    print("Total generated lines: %d" % total_lines)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
